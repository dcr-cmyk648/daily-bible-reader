#!/usr/bin/env node

import {mkdir, readFile, rename, writeFile} from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import {
  buildScheduleReviewPassages,
  applyScheduleReviewToResults
} from "./lib/mhc-review.mjs";
import {findSourceReportingPhrase} from "./lib/mhc-pipeline.mjs";
import {assertSchemaValid} from "./lib/schema-validator.mjs";
import {writePortableStores, writeScheduleAuditReport} from "./mhc-pipeline.mjs";

const ROOT = process.cwd();
const PRIVATE_ROOT = path.join(ROOT, "private-commentary", "mhc");
const PLAN_PATH = path.join(ROOT, "fixtures", "pilot-content", "plan.json");
const RUNTIME_SCHEMA_PATH = path.join(ROOT, "schemas", "mhc-runtime.schema.json");
const REVIEW_SCHEMA_PATH = path.join(ROOT, "schemas", "mhc-schedule-review.schema.json");

function usage() {
  return [
    "Usage:",
    "  node scripts/review-mhc-schedule.mjs prepare --reading READING_ID",
    "  node scripts/review-mhc-schedule.mjs apply --reading READING_ID --review PRIVATE_JSON",
    "",
    "prepare writes a hash-bound private candidate with false assertions. After direct source review,",
    "edit every required field and use apply. Apply fails closed if any generated byte changed."
  ].join("\n");
}

function parseArgs(argv) {
  const [command, ...rest] = argv;
  if (["--help", "-h", "help"].includes(command)) return {help: true};
  if (!["prepare", "apply"].includes(command)) throw new Error(usage());
  const options = {command};
  for (let index = 0; index < rest.length; index += 1) {
    const key = rest[index];
    if (!["--reading", "--review"].includes(key) || !rest[index + 1]) throw new Error(usage());
    options[key === "--reading" ? "readingId" : "reviewPath"] = rest[++index];
  }
  if (!/^[A-Za-z0-9][A-Za-z0-9._:-]{2,159}$/.test(String(options.readingId || ""))) throw new Error(usage());
  if (command === "apply" && !options.reviewPath) throw new Error(usage());
  return options;
}

async function readJson(filePath) {
  return JSON.parse(await readFile(filePath, "utf8"));
}

async function writeJsonAtomic(filePath, value) {
  await mkdir(path.dirname(filePath), {recursive: true});
  const temporary = `${filePath}.tmp-${process.pid}`;
  await writeFile(temporary, `${JSON.stringify(value, null, 2)}\n`, {encoding: "utf8", mode: 0o600});
  await rename(temporary, filePath);
}

function confinedPrivatePath(relativeOrAbsolute, label) {
  const resolved = path.resolve(ROOT, relativeOrAbsolute);
  const privateRoot = path.resolve(PRIVATE_ROOT);
  if (resolved !== privateRoot && !resolved.startsWith(`${privateRoot}${path.sep}`)) {
    throw new Error(`${label} must remain inside ignored private Matthew Henry storage.`);
  }
  return resolved;
}

async function loadReadingState(readingId) {
  const [plan, runtimeSchema] = await Promise.all([readJson(PLAN_PATH), readJson(RUNTIME_SCHEMA_PATH)]);
  const entry = plan.entries.find((candidate) => candidate.readingId === readingId);
  if (!entry || entry.kind !== "chapter") throw new Error(`${readingId} is not a chapter reading in the active plan.`);
  const root = path.join(PRIVATE_ROOT, "schedule", readingId);
  const auditPath = path.join(root, "audit.json");
  const audit = await readJson(auditPath);
  if (audit.reading_id !== readingId || audit.plan_version !== plan.planVersion || audit.audit_status === "generation_failed") {
    throw new Error(`${readingId} does not have a complete current-plan generation audit.`);
  }
  if (!Array.isArray(audit.passages) || audit.passages.length !== entry.passages.length) {
    throw new Error(`${readingId} audit does not cover the exact scheduled passage list.`);
  }
  const passageResults = [];
  for (let index = 0; index < entry.passages.length; index += 1) {
    const expected = entry.passages[index];
    const passage = audit.passages[index];
    if (passage.book_id !== expected.bookId || passage.chapter !== expected.chapter ||
        passage.verse_count !== expected.verseCount || !passage.runtime_path) {
      throw new Error(`${readingId} audit passage ${index + 1} does not match the active schedule.`);
    }
    const runtimePath = confinedPrivatePath(path.join(PRIVATE_ROOT, passage.runtime_path), "Runtime path");
    const runtime = await readJson(runtimePath);
    assertSchemaValid(runtime, runtimeSchema, {label: `${readingId} ${passage.book_id} ${passage.chapter} runtime`});
    if (runtime.book_id !== expected.bookId || runtime.chapter !== expected.chapter ||
        Object.keys(runtime.records || {}).length !== expected.verseCount) {
      throw new Error(`${readingId} runtime does not provide exact chapter coverage.`);
    }
    for (const [verseId, record] of Object.entries(runtime.records || {})) {
      for (const atomId of record.source_atom_ids || []) {
        if (!runtime.source_atoms || !runtime.source_atoms[atomId]) {
          throw new Error(`${readingId} ${verseId} cites missing atom ${atomId}.`);
        }
      }
    }
    passageResults.push({
      book_id: expected.bookId,
      chapter: expected.chapter,
      verse_count: expected.verseCount,
      runtime,
      runtimePath
    });
  }
  return {plan, entry, root, auditPath, audit, passageResults, runtimeSchema};
}

async function prepare(options) {
  const state = await loadReadingState(options.readingId);
  const candidatePath = path.join(state.root, "review-candidate.json");
  const candidate = {
    schema_version: "mhc-schedule-review/v1",
    reading_id: state.audit.reading_id,
    plan_version: state.audit.plan_version,
    prompt_version: state.audit.prompt_version,
    reviewed_at: null,
    reviewer: "",
    status: "in_review",
    scope: "every_condensation_and_every_cited_atom",
    assertions: {
      compared_every_condensation_with_cited_atoms: false,
      citations_resolve_to_exact_stored_atoms: false,
      no_idea_crossed_from_an_unrelated_range: false,
      no_outside_material_or_invented_distinction: false,
      no_prohibited_source_reporting_language: false,
      no_extended_source_copying: false,
      deterministic_validation_passed: false
    },
    findings: [],
    corrections: [],
    passages: buildScheduleReviewPassages(state)
  };
  await writeJsonAtomic(candidatePath, candidate);
  process.stdout.write(`Prepared private hash-bound review candidate: ${path.relative(ROOT, candidatePath)}\n`);
  process.stdout.write(`Review every condensation against its cited atoms in ${path.relative(ROOT, path.join(state.root, "audit.md"))}.\n`);
}

async function apply(options) {
  const state = await loadReadingState(options.readingId);
  const reviewPath = confinedPrivatePath(options.reviewPath, "Review path");
  const [review, reviewSchema] = await Promise.all([readJson(reviewPath), readJson(REVIEW_SCHEMA_PATH)]);
  assertSchemaValid(review, reviewSchema, {label: `${options.readingId} schedule review`});
  const promoted = applyScheduleReviewToResults({review, audit: state.audit, passageResults: state.passageResults});
  for (const result of promoted.passageResults) {
    assertSchemaValid(result.runtime, state.runtimeSchema, {label: `${options.readingId} corrected runtime`});
    for (const [verseId, record] of Object.entries(result.runtime.records || {})) {
      const sourceReportingPhrase = findSourceReportingPhrase(record && record.blurb);
      if (sourceReportingPhrase) {
        throw new Error(`${verseId} contains forbidden source-reporting phrase ${JSON.stringify(sourceReportingPhrase)}.`);
      }
      for (const atomId of record.source_atom_ids || []) {
        if (!result.runtime.source_atoms || !result.runtime.source_atoms[atomId]) {
          throw new Error(`${options.readingId} corrected ${verseId} cites missing atom ${atomId}.`);
        }
      }
    }
  }
  for (const result of promoted.passageResults) {
    await writeJsonAtomic(result.runtimePath, result.runtime);
  }
  const canonicalReviewPath = path.join(state.root, "review.json");
  await writeJsonAtomic(canonicalReviewPath, review);
  await writeJsonAtomic(state.auditPath, promoted.audit);
  await writeScheduleAuditReport(promoted.audit, promoted.passageResults, path.join(state.root, "audit.md"));
  const target = {
    preparedOn: promoted.audit.prepared_on,
    scheduleDate: promoted.audit.schedule_date,
    daysAhead: promoted.audit.days_ahead,
    timezone: promoted.audit.timezone,
    dayIndex: state.entry.dayIndex,
    entry: state.entry
  };
  await writePortableStores({
    plan: state.plan,
    window: null,
    scheduledResults: [{target, audit: promoted.audit, passageResults: promoted.passageResults}],
    writeWindow: false
  });
  process.stdout.write(`${options.readingId} is hash-bound and ${review.status}; the reviewed artifact is now current in the private Henry library.\n`);
}

const options = parseArgs(process.argv.slice(2));
if (options.help) {
  process.stdout.write(`${usage()}\n`);
} else (options.command === "prepare" ? prepare(options) : apply(options)).catch((error) => {
  process.stderr.write(`Matthew Henry schedule review failed: ${error.message}\n`);
  process.exitCode = 1;
});
